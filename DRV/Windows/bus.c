/* Static raw PDO enumeration for the functions integrated in a Time Card. */

#include "timecard.h"

/* {B5415088-5EE1-4D3A-8519-C3487370E0BF} */
const GUID GUID_DEVCLASS_TIMECARD =
    { 0xb5415088, 0x5ee1, 0x4d3a,
      { 0x85, 0x19, 0xc3, 0x48, 0x73, 0x70, 0xe0, 0xbf } };

typedef struct _TIMECARD_CHILD_DESCRIPTION {
    TIMECARD_SUBSYSTEM Subsystem;
    PCWSTR DeviceId;
    PCWSTR InstanceId;
    PCWSTR Description;
} TIMECARD_CHILD_DESCRIPTION;

